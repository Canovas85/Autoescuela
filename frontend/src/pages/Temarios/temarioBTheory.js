export function getTemarioBTheory(temario) {
  if (!temario) {
    return null;
  }

  const byId = temasPermisoB[temario.id];

  if (byId) {
    return {
      ...byId,
      miniTest: miniTestsPermisoB[temario.id] || [],
    };
  }

  const byOrder = Object.entries(temasPermisoB).find(([key]) => {
    const expectedOrder = Number(key.split("-")[1]);
    return expectedOrder === Number(temario.orden);
  });

  if (!byOrder) {
    return null;
  }

  const [temarioKey, temarioValue] = byOrder;

  return {
    ...temarioValue,
    miniTest: miniTestsPermisoB[temarioKey] || [],
  };
}
